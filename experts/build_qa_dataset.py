"""
build_qa_dataset.py — Build a single-tool QA dataset for a lightweight expert.

Stage-1 (Gain-Driven Tool Selection) trains one expert per forensic tool. Each
training sample pairs the original image with that tool's map and asks the model
to classify real/fake (+ boxes). This script emits those samples in ms-swift
format:

    {
      "messages": [
        {"role": "user",      "content": "<image><image>...tool-specific prompt..."},
        {"role": "assistant", "content": "<answer>real</answer>"
                                       | "<answer>fake, <bbox>...</bbox-tokens></answer>"}
      ],
      "images": [<original_image>, <tool_map>],     # order: image first, tool map second
      "objects": {"bbox": [[x1,y1,x2,y2], ...]},     # fake only
      "label": 0 | 1
    }

The assistant answer emits one `<bbox>` token per ground-truth box
(e.g. two boxes -> "<answer>fake, <bbox><bbox></answer>").

Inputs
------
--fake_json : <dataset>.json (forged_path + bboxes) from data/prepare/mask_to_bbox.py  -> fake samples (label 1)
--au_dir    : a directory of authentic images                                          -> real samples (label 0)
--toolmap_dir : tool-map root generated by data/prepare/generate_tool_maps.py

Example
-------
python experts/build_qa_dataset.py --tool ela \
    --fake_json   <DATA_ROOT>/832x/casia2_tp/casia2_tp.json \
    --au_dir      <DATA_ROOT>/832x/casia2_au \
    --toolmap_dir <TOOLS_MAPS_ROOT> \
    --out         casia2_ela_qa.json
"""

import os
import json
import glob
import random
import argparse
from pathlib import Path

# tool -> (tool-map filename suffix, user prompt).  Suffixes match config_SFT.get_tool_path.
# `notool` has suffix None: a single-image (no tool map) baseline conversation.
TOOLS = {
    "notool": (
        None,
        "<image>Please analyze this image to detect manipulation.\n"
        "If the image is authentic, output <answer>real</answer>.\n"
        "If manipulated, detect and output fake and the bounding box of the forged region immediately."
    ),
    "ela": (
        "_ELA.png",
        "<image><image>The first image is the original input, and the second is its ELA heatmap. "
        "In the heatmap, red or bright areas represent high error levels.\n"
        "Please compare the two images to detect manipulation. Focus on inconsistencies where the ELA "
        "brightness does not match the texture complexity of the original image (e.g., a smooth area "
        "showing high error).\n"
        "If the image is authentic, output <answer>real</answer>.\n"
        "If manipulated, detect and output fake and the bounding box of the forged region immediately."
    ),
    "fft": (
        "_FFT.png",
        "<image><image>The first image is the original input, and the second is its FFT High-Frequency "
        "heatmap. In the heatmap, red or bright areas represent strong high-frequency energy (edges, "
        "textures, or noise), while blue areas indicate smooth low-frequency regions.\n"
        "Please compare the two images to detect manipulation. \n\n"
        "**Important:** Natural sharp textures (e.g., hair, grass, complex patterns) will normally appear "
        "bright/red. Do not interpret high energy solely as manipulation.\n\n"
        "Instead, focus on **anomalies and inconsistencies**:\n"
        "1. **Unnatural Boundaries:** Look for objects with glowing edges or halos that are significantly "
        "sharper than natural edges in the image.\n"
        "2. **Frequency Mismatch:** Identify regions where the noise level or sharpness drastically differs "
        "from the surrounding background without a valid semantic reason (e.g., a blurry object in a sharp "
        "environment or vice versa).\n"
        "If the image is authentic, output <answer>real</answer>.\n"
        "If manipulated, detect and output fake and the bounding box of the forged region immediately."
    ),
    "npp": (
        "_NPP.png",
        "<image><image>The first image is the original. The second is its noise map. \n\n"
        "If the image is authentic, output <answer>real</answer>.\n"
        "If manipulated, detect and output fake and the bounding box of the forged region immediately."
    ),
    "zoom_in": (
        "_zoomin.png",
        "<image><image>The first image is the original input, and the second is a zoomed-in crop of a "
        "suspicious region for fine-grained inspection.\n"
        "Please examine the magnified region for subtle manipulation artifacts, such as inconsistent "
        "textures, unnatural edges or blending boundaries, noise or lighting that does not match the "
        "surrounding content, or resampling and warping traces.\n"
        "If the image is authentic, output <answer>real</answer>.\n"
        "If manipulated, detect and output fake and the bounding box of the forged region immediately."
    ),
}

IMG_EXTS = (".png", ".jpg", ".jpeg", ".bmp", ".tif", ".tiff")


def answer_for(bboxes):
    if bboxes:
        return f"<answer>fake, {'<bbox>' * len(bboxes)}</answer>"
    return "<answer>real</answer>"


def portable_path(path):
    """Prefer a repository-relative path when the file is under the cwd."""
    absolute = os.path.abspath(path)
    relative = os.path.relpath(absolute, os.getcwd())
    return relative if relative != ".." and not relative.startswith(f"..{os.sep}") else absolute


def dataset_name_from_path(path):
    for parent in Path(path).parents:
        if parent.name.lower().endswith(("_tp", "_au")):
            return parent.name
    return None


def toolmap_path(orig_path, toolmap_dir, suffix):
    filename = f"{Path(orig_path).stem}{suffix}"
    tool_name = suffix.removeprefix("_").removesuffix(".png")
    dataset_name = dataset_name_from_path(orig_path)
    candidates = []
    if dataset_name:
        candidates.append(os.path.join(toolmap_dir, dataset_name, tool_name, filename))
    # Backward compatibility with the earlier flat <root>/<tool>/ layout and
    # with callers that directly pass one tool directory.
    candidates.extend([
        os.path.join(toolmap_dir, tool_name, filename),
        os.path.join(toolmap_dir, filename),
    ])
    return next((path for path in candidates if os.path.exists(path)), candidates[0])


def main():
    ap = argparse.ArgumentParser(description="Build a single-tool QA dataset")
    ap.add_argument("--tool", required=True, choices=list(TOOLS.keys()))
    ap.add_argument("--toolmap_dir", default=None,
                    help="root containing <dataset>/<tool>/ maps (not needed for --tool notool)")
    ap.add_argument("--fake_json", default=None, help="tampered <dataset>.json (forged_path + bboxes)")
    ap.add_argument("--au_dir", default=None, help="directory of authentic images")
    ap.add_argument("--out", required=True, help="output QA json")
    ap.add_argument("--keep_missing_toolmap", action="store_true",
                    help="keep samples even if the tool map file is absent (default: skip them)")
    ap.add_argument("--balance", action="store_true",
                    help="downsample authentic images to match the fake count (avoid real/fake bias)")
    ap.add_argument("--max_real", type=int, default=None,
                    help="hard cap on authentic samples (overrides --balance target)")
    ap.add_argument("--seed", type=int, default=42, help="RNG seed for authentic sampling")
    args = ap.parse_args()

    suffix, prompt = TOOLS[args.tool]
    if suffix is not None and not args.toolmap_dir:
        ap.error(f"--toolmap_dir is required for --tool {args.tool}")
    records, skipped = [], 0

    def add(orig_path, bboxes, label):
        nonlocal skipped
        if suffix is None:                       # notool: single image, no tool map
            images = [orig_path]
        else:
            tmap = toolmap_path(orig_path, args.toolmap_dir, suffix)
            if not args.keep_missing_toolmap and not os.path.exists(tmap):
                skipped += 1
                return
            images = [orig_path, tmap]
        rec = {
            "messages": [
                {"role": "user", "content": prompt},
                {"role": "assistant", "content": answer_for(bboxes)},
            ],
            "images": images,
            "label": label,
        }
        if label == 1:
            rec["objects"] = {"bbox": bboxes}
        records.append(rec)

    # fake samples first (so we know the target count for balancing)
    if args.fake_json:
        fake_json_dir = os.path.dirname(os.path.abspath(args.fake_json))
        with open(args.fake_json) as f:
            for e in json.load(f):
                fp, bb = e.get("forged_path"), e.get("bboxes") or []
                if fp and bb:
                    if not os.path.isabs(fp):
                        fp = os.path.join(fake_json_dir, fp)
                    fp = portable_path(fp)
                    add(fp, bb, 1)
    n_fake = sum(1 for r in records if r["label"] == 1)

    # real samples (optionally downsampled to match the fake count)
    if args.au_dir:
        au_paths = [p for p in sorted(glob.glob(os.path.join(args.au_dir, "**", "*"), recursive=True))
                    if p.lower().endswith(IMG_EXTS)]
        target = args.max_real if args.max_real is not None else (n_fake if args.balance else None)
        if target is not None:
            random.Random(args.seed).shuffle(au_paths)
        added_real = 0
        for p in au_paths:
            if target is not None and added_real >= target:
                break
            before = len(records)
            add(portable_path(p), [], 0)
            if len(records) > before:
                added_real += 1

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        json.dump(records, f, indent=4)

    n_fake = sum(1 for r in records if r["label"] == 1)
    print(f"[DONE] tool={args.tool}  wrote {len(records)} samples "
          f"(fake={n_fake}, real={len(records) - n_fake}) -> {args.out}")
    if skipped:
        print(f"       skipped {skipped} samples with a missing tool map "
              f"(use --keep_missing_toolmap to keep them)")


if __name__ == "__main__":
    main()
